#!/usr/bin/env bash
# Install the LitCoin development sample on the prepared AWS k3s host.
# The presigned dump URL is intentionally accepted as an argument and is never written to disk.
set -euo pipefail

usage() {
  cat >&2 <<'EOF'
Usage: install.sh <namespace> <presigned-dump-url> <dump-sha256> <artifacts-sha256>

Run this on the prepared instance from a checkout of the branch. The dump URL must remain
valid until the download init container finishes; AWS presigned URLs generated by the runbook
expire after two hours.
EOF
  exit 2
}

[ "$#" -eq 4 ] || usage
NAMESPACE="$1"
DUMP_URL="$2"
DUMP_SHA256="$3"
ARTIFACTS_SHA256="$4"

[[ "$DUMP_SHA256" =~ ^[[:xdigit:]]{64}$ ]] || {
  printf 'ERROR: dump SHA-256 must be exactly 64 hexadecimal characters.\n' >&2
  exit 2
}
[[ "$ARTIFACTS_SHA256" =~ ^[[:xdigit:]]{64}$ ]] || {
  printf 'ERROR: artifacts SHA-256 must be exactly 64 hexadecimal characters.\n' >&2
  exit 2
}

script_dir="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)"
chart_dir="$script_dir/../helm/kgb-mcp"
values_file="$script_dir/values-aws-test.yaml"
release='kgb-mcp'

[ -d "$chart_dir" ] || { printf 'ERROR: chart not found: %s\n' "$chart_dir" >&2; exit 1; }
[ -f "$values_file" ] || { printf 'ERROR: values file not found: %s\n' "$values_file" >&2; exit 1; }
kubectl get namespace "$NAMESPACE" >/dev/null

# Prompts for passwords; neither password is an install-script argument.
bash "$script_dir/../create_neo4j_secret.sh" "$NAMESPACE"

helm upgrade --install "$release" "$chart_dir" \
  --namespace "$NAMESPACE" \
  -f "$values_file" \
  --set-string "neo4j.dumpUrl=$DUMP_URL" \
  --set-string "neo4j.dumpSha256=$DUMP_SHA256" \
  --set-string "mcp.artifactsSha256=$ARTIFACTS_SHA256" \
  --wait --wait-for-jobs --timeout 30m

kubectl -n "$NAMESPACE" rollout status "statefulset/${release}-neo4j" --timeout=30m
printf '\nBolt Service:\n'
kubectl -n "$NAMESPACE" get service "${release}-neo4j" -o wide
printf '\nServiceLB pod (kube-system):\n'
kubectl -n kube-system get pods -l "svccontroller.k3s.cattle.io/svcname=${release}-neo4j" -o wide
